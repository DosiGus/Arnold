type CatalogId = (typeof MOBILITY_CATALOG)[number]["id"];
/** The catalog IDs, in catalog order. */
export const MOBILITY_EXERCISE_IDS = MOBILITY_CATALOG.map((e) => e.id) as [
  CatalogId,
  ...CatalogId[],
];
export const MobilityExerciseIdSchema = z.enum(MOBILITY_EXERCISE_IDS);
export type MobilityExerciseId = z.infer<typeof MobilityExerciseIdSchema>;

const BY_ID: ReadonlyMap<string, MobilityExercise> = new Map(
  MOBILITY_CATALOG.map((e) => [e.id, e]),
);

/** The catalog entry of an ID, or null for an unknown ID. */
export function mobilityExercise(id: string): MobilityExercise | null {
  return BY_ID.get(id) ?? null;
}
