/**
 * Mobility: the fixed exercise catalog (ARN-MOB, D-MOB-04).
 *
 * Only data and pure lookups live here. The catalog is closed: Arnold builds
 * every mobility routine from these 40 entries and the timing engine
 * (`src/analytics/mobility/timing.ts`) decides the seconds. The model never
 * invents an exercise or a duration.
 *
 * Seconds are per side (`per_side`); for `reps` and `flow` they are the
 * length of the block. All seconds are multiples of 5, so the engine's 5 s
 * rounding never leaves the bounds. `morning_ok` is true exactly for the
 * exercises done standing or at a wall: the morning routine needs no mat.
 *
 * Cues are calm execution hints, never a health promise.
 *
 * A leaf module: it imports nothing but Zod, so the stored rows, the plan and
 * the onboarding contracts can all build on it without a cycle.
 */
import { z } from "zod";

export const MOBILITY_CATALOG_VERSION = "mob-1";

/** Body areas a routine can address. A preference, never a diagnosis. */
export const MOBILITY_AREAS = [
  "neck",
  "shoulders",
  "upper_back",
  "lower_back",
  "hips",
  "hamstrings",
  "calves_ankles",
  "wrists",
] as const;
export const MobilityAreaSchema = z.enum(MOBILITY_AREAS);
export type MobilityArea = z.infer<typeof MobilityAreaSchema>;

export const MOBILITY_MODES = ["hold", "reps", "flow"] as const;
export const MobilityModeSchema = z.enum(MOBILITY_MODES);
export type MobilityMode = z.infer<typeof MobilityModeSchema>;

export const MOBILITY_POSITIONS = [
  "standing",
  "wall",
  "floor",
  "seated",
] as const;
export const MobilityPositionSchema = z.enum(MOBILITY_POSITIONS);
export type MobilityPosition = z.infer<typeof MobilityPositionSchema>;

/** Lengths shared by the catalog, the watch payloads and the tests. */
export const MOBILITY_TEXT_LIMITS = {
  id: 40,
  name: 22,
  cue: 40,
} as const;

/** Repetitions of a `reps` exercise. */
export const MOBILITY_REPS_MIN = 4;
export const MOBILITY_REPS_MAX = 15;

export type MobilityExercise = {
  readonly id: string;
  readonly name_de: string;
  readonly name_en: string;
  readonly areas: readonly MobilityArea[];
  readonly mode: MobilityMode;
  readonly per_side: boolean;
  /** Seconds per side; for reps and flow the length of the block. */
  readonly default_s: number;
  readonly min_s: number;
  readonly max_s: number;
  /** Only for mode reps (4–15), otherwise null. */
  readonly reps: number | null;
  readonly position: MobilityPosition;
  /** True exactly for standing and wall exercises (no mat). */
  readonly morning_ok: boolean;
  readonly cue_de: string;
  readonly cue_en: string;
};

type Entry<I extends string> = Omit<MobilityExercise, "morning_ok" | "id"> & {
  readonly id: I;
};
const entry = <const I extends string>(
  e: Entry<I>,
): MobilityExercise & { readonly id: I } =>
  Object.freeze({
    ...e,
    areas: Object.freeze([...e.areas]),
    morning_ok: e.position === "standing" || e.position === "wall",
  });

