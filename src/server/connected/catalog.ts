import {
  ArnoldDatasetSchema,
  type ArnoldDataset,
} from "../../shared/arnold-schema-v1.js";

/** A small exercise catalog; no invented workouts, plans, sets or start weights. */
export function newTrackerDataset(trackerId: string): ArnoldDataset {
  const config = {
    schema_id: "arnold.training_raw",
    schema_version: "1.0.0",
    template_version: "1.0.0",
    file_role: "USER_TRACKER",
    tracker_id: trackerId,
    unit_mass: "kg",
    date_storage: "ISO-8601",
    raw_data_policy: "NO_CALCULATED_COLUMNS",
    onboarding_storage: "BACKEND_ONLY",
    plan_history: "IMMUTABLE_VERSION_IDS",
    write_policy: "MCP_BACKEND_ONLY",
    master_data_policy: "NO_REAL_USER_DATA",
    deleted_record_policy: "TOMBSTONE",
    schema_fingerprint: "CONFIG|EXERCISES|PLANS|PLAN_ITEMS|WORKOUTS|SETS",
  };
  const catalog = [
    [
      "bench-press",
      "Bankdrücken",
      "Langhantel",
      "Brust",
      "press",
      "total",
      "bilateral_simultaneous",
      1,
    ],
    [
      "dumbbell-bench-press",
      "Kurzhantel-Bankdrücken",
      "Kurzhantel",
      "Brust",
      "press",
      "per_implement",
      "bilateral_simultaneous",
      2,
    ],
    [
      "lateral-raise",
      "Seitheben",
      "Kurzhantel",
      "Schultern",
      "raise",
      "per_implement",
      "bilateral_simultaneous",
      2,
    ],
    [
      "one-arm-row",
      "Rudern einarmig",
      "Kurzhantel",
      "Rücken",
      "row",
      "per_implement",
      "unilateral",
      1,
    ],
    [
      "lat-pulldown",
      "Latzug",
      "Maschine",
      "Rücken",
      "pull",
      "machine_display",
      "bilateral_simultaneous",
      1,
    ],
    [
      "pull-up",
      "Klimmzüge",
      "Körpergewicht",
      "Rücken",
      "pull",
      "bodyweight_only",
      "bilateral_simultaneous",
      1,
    ],
    [
      "squat",
      "Kniebeugen",
      "Langhantel",
      "Beine",
      "squat",
      "total",
      "bilateral_simultaneous",
      1,
    ],
    [
      "leg-press",
      "Beinpresse",
      "Maschine",
      "Beine",
      "press",
      "machine_display",
      "bilateral_simultaneous",
      1,
    ],
    [
      "leg-curl",
      "Beinbeuger",
      "Maschine",
      "Beine",
      "curl",
      "machine_display",
      "bilateral_simultaneous",
      1,
    ],
  ];
  const timestamp = new Date().toISOString();
  return ArnoldDatasetSchema.parse({
    config,
    configEntries: Object.entries(config).map(([key, value]) => ({
      key,
      value,
      description: null,
    })),
    exercises: catalog.map(
      ([
        exercise_id,
        name_de,
        equipment,
        primary_muscle,
        family_key,
        default_load_basis,
        default_execution_mode,
        default_implement_count,
      ]) => ({
        exercise_id,
        name_de,
        name_en: null,
        equipment,
        primary_muscle,
        family_key,
        variant_key: exercise_id,
        default_load_basis,
        default_execution_mode,
        default_implement_count,
        status: "active",
        created_at_utc: timestamp,
        updated_at_utc: timestamp,
        row_revision: 1,
      }),
    ),
    plans: [],
    planItems: [],
    workouts: [],
    sets: [],
  });
}
